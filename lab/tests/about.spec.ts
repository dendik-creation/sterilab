import { test, expect } from '@playwright/test';

test('About returns to each origin and Home bypasses startup', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Tentang SteriLab' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Ketuk di mana saja untuk melanjutkan' }).click({ timeout: 30000 });
  await page.evaluate(() => localStorage.setItem('about-test-preserve', 'unchanged'));
  const about = page.getByRole('button', { name: 'Tentang SteriLab' });
  const back = page.getByRole('button', { name: 'Kembali' });
  const heading = page.getByRole('heading', { name: 'TENTANG STERILAB' });
  const checkAbout = async () => {
    const a = await about.boundingBox();
    const b = await page.getByRole('button', { name: /(?:Matikan|Nyalakan) suara/ }).boundingBox();
    expect(a!.x + a!.width).toBeLessThanOrEqual(b!.x);
    await about.click();
    await expect(heading).toBeVisible();
    await expect(page.getByText("Programmer (Dendi' Setiawan)")).toBeVisible();
    await expect(page.locator('audio[data-sterilab-voice]')).toHaveCount(0);
  };
  await checkAbout();
  await page.screenshot({ path: `screenshots/about-${testInfo.project.name}.png` });
  await page.getByRole('button', { name: 'Matikan suara' }).click();
  await expect(page.getByRole('button', { name: 'Nyalakan suara' })).toBeVisible();
  await back.click();
  await expect(page.getByRole('button', { name: 'Mulai Menjelajah' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Nyalakan suara' })).toBeVisible();
  await page.getByRole('button', { name: 'Nyalakan suara' }).click();
  await page.screenshot({ path: `screenshots/home-${testInfo.project.name}.png` });
  await page.getByRole('button', { name: 'Mulai Menjelajah' }).click();
  await checkAbout();
  await back.click();
  await expect(page.getByRole('button', { name: 'Lanjut', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Lanjut', exact: true }).click();
  const hook = await page.getByTestId('case-narration').elementHandle();
  await checkAbout();
  expect(await hook!.evaluate((el: HTMLAudioElement) => el.paused)).toBe(true);
  await back.click();
  await page.getByRole('button', { name: 'Lanjut Briefing' }).click();
  await page.screenshot({ path: `screenshots/dashboard-${testInfo.project.name}.png` });
  await checkAbout();
  await back.click();
  await expect(page.getByRole('button', { name: /Mulai Misi 1/ })).toBeVisible();
  await page.getByRole('button', { name: /Mulai Misi 1/ }).click();
  await expect(about).toHaveCount(0);
  await page.getByRole('button', { name: 'Menu Utama' }).click();
  await expect(page.getByRole('button', { name: 'Mulai Menjelajah' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Ketuk di mana saja untuk melanjutkan' })).toHaveCount(0);
  expect(await page.evaluate(() => localStorage.getItem('about-test-preserve'))).toBe('unchanged');
  expect(errors).toEqual([]);
});

