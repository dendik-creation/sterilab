test('Tentang button follows the surrounding controls during transitions', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Ketuk di mana saja untuk melanjutkan' }).click({ timeout: 30000 });
  const about = page.getByRole('button', { name: 'Tentang SteriLab' });
  await expect(about).toHaveClass(/sterilab-bubble-in/);
  await about.click();
  await expect(about).toHaveClass(/sterilab-bubble-out/);
  await expect(page.getByRole('heading', { name: 'TENTANG STERILAB' })).toBeVisible();
  const badge = page.locator('.ai-disclosure');
  await expect(badge).toHaveClass(/ai-disclosure--horizontal/);
  const badgeBox = await badge.boundingBox();
  const cardBox = await page.locator('.about-card').boundingBox();
  expect(badgeBox!.x).toBeGreaterThan(cardBox!.x);
  await page.getByRole('button', { name: 'Kembali' }).click();
  await expect(page.locator('.about-card')).toHaveClass(/sterilab-bubble-out/);
  await expect(badge).toHaveClass(/sterilab-bubble-out/);
  await page.getByRole('button', { name: 'Mulai Menjelajah' }).click();
  await expect(about).toHaveClass(/sterilab-bubble-in/);
  await about.click();
  await expect(about).toHaveClass(/sterilab-bubble-out/);
  await expect(page.getByRole('heading', { name: 'TENTANG STERILAB' })).toBeVisible();
});
